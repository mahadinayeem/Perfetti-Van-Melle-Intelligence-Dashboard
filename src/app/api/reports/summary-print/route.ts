import { NextRequest, NextResponse } from 'next/server';
import { getValidToken } from '@/lib/sokrioClient';
import axios from 'axios';
import * as fs from 'fs';
import * as path from 'path';
import * as XLSX from 'xlsx';

export const dynamic = 'force-dynamic';

export interface SummaryPrintRecord {
  id: string;
  cluster: string;
  area: string;
  territory: string;
  dbCodeAutogenerated: string;
  dbCode: string | number;
  dbName: string;
  dbType: string;
  printerType: string;
  srPositionCode: string;
  srCode: string | number;
  srName: string;
  orderDate: string;
  printingDate: string;
  printingTime: string;
}

const memoryCache = new Map<string, { records: SummaryPrintRecord[]; meta: any; timestamp: number }>();
const CACHE_TTL_MS = 2 * 60 * 1000;

const SR_METADATA: Record<string, { srPositionCode: string; territory: string }> = {
  '54506': { srPositionCode: 'DM-057', territory: 'Jatra Bari' },
  '51639': { srPositionCode: 'DM-217', territory: 'Jatra Bari' },
  '53995': { srPositionCode: 'DM-057', territory: 'Jatra Bari' },
  '54233': { srPositionCode: 'DM-059', territory: 'Jatra Bari' },
  '20145': { srPositionCode: 'COM-022', territory: 'Jatra Bari' },
};

function getSampleExcelData(): SummaryPrintRecord[] {
  try {
    const filePath = path.join(process.cwd(), 'Report Sample.xlsx');
    if (!fs.existsSync(filePath)) return [];
    const buf = fs.readFileSync(filePath);
    const wb = XLSX.read(buf, { type: 'buffer' });
    const sheet = wb.Sheets['Summary Print Report'];
    if (!sheet) return [];
    const raw: any[][] = XLSX.utils.sheet_to_json(sheet, { header: 1 });
    if (raw.length < 2) return [];

    const headers = raw[0].map(h => String(h || '').trim());
    return raw.slice(1).map((r, idx) => {
      const obj: Record<string, any> = {};
      headers.forEach((h, colIdx) => {
        obj[h] = r[colIdx];
      });
      return {
        id: `summary-print-${idx + 1}`,
        cluster: String(obj['Cluster'] || 'Central'),
        area: String(obj['Area'] || 'Central South'),
        territory: String(obj['Territory'] || 'Jatra Bari'),
        dbCodeAutogenerated: '', // Blank
        dbCode: obj['DB Code'] || 102267,
        dbName: String(obj['DB Name'] || 'M/S Ahamed Enterprise'),
        dbType: '', // Blank as per rule
        printerType: '', // Blank
        srPositionCode: String(obj['SR Position Code'] || 'DM-057'),
        srCode: obj['SR Code'] || '',
        srName: String(obj['SR Name'] || ''),
        orderDate: String(obj['Order Date'] || ''),
        printingDate: String(obj['Printing Date'] || ''),
        printingTime: String(obj['Printing Time'] || ''),
      };
    });
  } catch (e) {
    console.error('[Summary Print Report] Failed to read sample excel:', e);
    return [];
  }
}

async function fetchLiveSummaryPrintsFromSokrio(): Promise<SummaryPrintRecord[]> {
  const token = await getValidToken();
  const url = 'https://pvm.core.sokrio.com/api/v1/invoices?per_page=150';

  const res = await axios.get(url, {
    headers: { Authorization: `Bearer ${token}`, Accept: 'application/json' },
    timeout: 30000,
  });

  const invoices: any[] = res.data?.invoices || res.data?.data || [];
  if (invoices.length === 0) return [];

  // Group by SR code and order date
  const grouped: Record<string, SummaryPrintRecord> = {};

  invoices.forEach((inv, idx) => {
    const srCode = String(inv.creator?.code || inv.ordered_by?.code || '').trim();
    if (!srCode) return;

    const srName = String(inv.creator?.name || inv.ordered_by?.name || `SR ${srCode}`).trim();
    const srMeta = SR_METADATA[srCode] || { srPositionCode: 'DM-057', territory: 'Jatra Bari' };

    const createdAt = inv.created_at || '';
    const parts = createdAt.split(' ');
    const printingDate = parts[0] || '';
    const printingTime = parts[1] || '';
    const orderDate = inv.order?.order_date || printingDate;

    const groupKey = `${srCode}_${orderDate}_${printingDate}`;

    if (!grouped[groupKey]) {
      grouped[groupKey] = {
        id: `summary-print-live-${idx + 1}`,
        cluster: 'Central',
        area: 'Central South',
        territory: srMeta.territory,
        dbCodeAutogenerated: '', // Blank
        dbCode: 102267,
        dbName: 'M/S Ahamed Enterprise',
        dbType: '', // Blank as per rule
        printerType: '', // Blank
        srPositionCode: srMeta.srPositionCode,
        srCode: Number(srCode) || srCode,
        srName,
        orderDate,
        printingDate,
        printingTime,
      };
    }
  });

  return Object.values(grouped);
}

export async function GET(request: NextRequest) {
  try {
    const { searchParams } = new URL(request.url);
    const now = new Date();
    const todayStr = `${now.getFullYear()}-${String(now.getMonth() + 1).padStart(2, '0')}-${String(now.getDate()).padStart(2, '0')}`;
    const startOfMonth = `${now.getFullYear()}-${String(now.getMonth() + 1).padStart(2, '0')}-01`;

    const startDate = searchParams.get('startDate') || startOfMonth;
    const endDate = searchParams.get('endDate') || todayStr;
    const forceRefresh = searchParams.get('refresh') === 'true';

    const cacheKey = `summary_print_${startDate}_${endDate}`;
    if (!forceRefresh) {
      const cached = memoryCache.get(cacheKey);
      if (cached && Date.now() - cached.timestamp < CACHE_TTL_MS) {
        return NextResponse.json({
          success: true,
          data: cached.records,
          meta: cached.meta,
          cached: true,
        });
      }
    }

    let records = await fetchLiveSummaryPrintsFromSokrio();
    let source = 'sokrio_live_api';

    if (records.length === 0) {
      records = getSampleExcelData();
      source = 'sample_excel_fallback';
    }

    const meta = {
      totalRecords: records.length,
      startDate,
      endDate,
      source,
    };

    memoryCache.set(cacheKey, {
      records,
      meta,
      timestamp: Date.now(),
    });

    return NextResponse.json({
      success: true,
      data: records,
      meta,
      cached: false,
    });
  } catch (error: any) {
    console.error('[Summary Print Report API Error]:', error);
    const fallback = getSampleExcelData();
    return NextResponse.json({
      success: true,
      data: fallback,
      meta: {
        totalRecords: fallback.length,
        source: 'sample_excel_error_fallback',
        error: error.message,
      },
      cached: false,
    });
  }
}
