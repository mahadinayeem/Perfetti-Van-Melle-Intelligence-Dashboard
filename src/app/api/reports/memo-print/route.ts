export interface MemoPrintRecord {
  id: string;
  cluster: string;
  area: string;
  territory: string;
  dbCodeAutogenerated: string;
  dbCode: string | number;
  dbName: string;
  dbType: string;
  printerType: string;
  srPositionCode: string;
  srCode: string | number;
  srName: string;
  orderMemoNo: string | number;
  printingMemoNo: string | number;
  orderDate: string;
  printingDate: string;
  printingTime: string;
}

const memoryCache = new Map<string, { records: MemoPrintRecord[]; meta: any; timestamp: number }>();
const CACHE_TTL_MS = 2 * 60 * 1000;

function formatDateToMMDDYYYY(val: any): string {
  if (!val) return '';
  const s = String(val).trim();
  if (s.includes('-')) {
    const p = s.split(' ')[0].split('-');
    if (p.length === 3) {
      if (p[0].length === 4) {
        // YYYY-MM-DD -> MM/DD/YYYY
        return `${p[1].padStart(2, '0')}/${p[2].padStart(2, '0')}/${p[0]}`;
      } else if (p[2].length === 4) {
        // DD-MM-YYYY -> MM/DD/YYYY
        return `${p[1].padStart(2, '0')}/${p[0].padStart(2, '0')}/${p[2]}`;
      }
    }
  }
  if (s.includes('/')) {
    const p = s.split(' ')[0].split('/');
    if (p.length === 3) {
      if (p[0].length === 4) {
        // YYYY/MM/DD -> MM/DD/YYYY
        return `${p[1].padStart(2, '0')}/${p[2].padStart(2, '0')}/${p[0]}`;
      } else if (p[2].length === 4) {
        return `${p[0].padStart(2, '0')}/${p[1].padStart(2, '0')}/${p[2]}`;
      }
    }
  }
  const d = new Date(val);
  if (!isNaN(d.getTime())) {
    const mm = String(d.getMonth() + 1).padStart(2, '0');
    const dd = String(d.getDate()).padStart(2, '0');
    return `${mm}/${dd}/${d.getFullYear()}`;
  }
  return s;
}

function formatTimeTo12Hour(val: any): string {
  if (!val) return '';
  const s = String(val).trim();
  const timePart = s.includes(' ') && s.includes(':') ? (s.split(' ').find(x => x.includes(':')) || s) : s;
  const match = timePart.match(/(\d{1,2}):(\d{2})(?::(\d{2}))?\s*(am|pm)?/i);
  if (match) {
    let [_, hStr, mStr, , ampm] = match;
    let h = parseInt(hStr, 10);
    const m = mStr.padStart(2, '0');
    let period = (ampm || '').toUpperCase();
    if (!period) {
      period = h >= 12 ? 'PM' : 'AM';
      if (h > 12) h -= 12;
      if (h === 0) h = 12;
    }
    return `${String(h).padStart(2, '0')}:${m} ${period}`;
  }
  return s;
}

async function fetchLiveInvoicesFromSokrio(startDate: string, endDate: string): Promise<MemoPrintRecord[]> {
  const token = await getValidToken();
  const url = 'https://pvm.core.sokrio.com/api/v1/invoices?per_page=150';

  const [res, srOrgMap] = await Promise.all([
    axios.get(url, {
      headers: { Authorization: `Bearer ${token}`, Accept: 'application/json' },
      timeout: 30000,
    }),
    fetchLiveSrOrganizationMap().catch(() => new Map<string, any>()),
  ]);

  const invoices: any[] = res.data?.invoices || res.data?.data || [];
  if (invoices.length === 0) return [];

  // Group live invoices by SR Code + Order Date to aggregate daily order & printing memo counts
  const groups: Record<string, {
    srCode: string;
    srName: string;
    orderDate: string;
    printingDate: string;
    orderMemoCount: number;
    printedMemoCount: number;
    latestPrintingTime: string;
  }> = {};

  invoices.forEach(inv => {
    const srCode = String(inv.creator?.code || inv.ordered_by?.code || '').trim();
    if (!srCode) return;
    const org = srOrgMap.get(srCode);
    const srName = String(inv.creator?.name || inv.ordered_by?.name || org?.srName || `SR ${srCode}`).trim();
    const createdAt = inv.created_at || '';
    const parts = createdAt.split(' ');
    const printingDate = parts[0] || '';
    const printingTime = parts.slice(1).join(' ') || '';
    const orderDate = inv.order?.order_date || printingDate;

    // Filter by date range if applicable
    if (orderDate && startDate && endDate) {
      if (orderDate < startDate || orderDate > endDate) return;
    }

    const groupKey = `${srCode}_${orderDate}`;
    if (!groups[groupKey]) {
      groups[groupKey] = {
        srCode,
        srName,
        orderDate,
        printingDate,
        orderMemoCount: 0,
        printedMemoCount: 0,
        latestPrintingTime: '',
      };
    }

    groups[groupKey].orderMemoCount += 1;
    groups[groupKey].printedMemoCount += 1;

    if (printingTime && (!groups[groupKey].latestPrintingTime || printingTime > groups[groupKey].latestPrintingTime)) {
      groups[groupKey].latestPrintingTime = printingTime;
      groups[groupKey].printingDate = printingDate;
    }
  });

  return Object.values(groups).map((g, idx) => {
    const org = srOrgMap.get(g.srCode);
    return {
      id: `memo-live-${g.srCode}-${g.orderDate}-${idx + 1}`,
      cluster: org?.cluster || 'Central',
      area: org?.area || '',
      territory: org?.territory || '',
      dbCodeAutogenerated: 'MD11239',
      dbCode: Number(org?.dbCode) || org?.dbCode || '',
      dbName: org?.dbName || '',
      dbType: 'Main DB',
      printerType: 'Web',
      srPositionCode: org?.srPositionCode || '',
      srCode: Number(g.srCode) || g.srCode,
      srName: g.srName || org?.srName || '',
      orderMemoNo: g.orderMemoCount,
      printingMemoNo: g.printedMemoCount,
      orderDate: formatDateToMMDDYYYY(g.orderDate),
      printingDate: formatDateToMMDDYYYY(g.printingDate || g.orderDate),
      printingTime: formatTimeTo12Hour(g.latestPrintingTime),
    };
  });
}

export async function GET(request: NextRequest) {
  try {
    const { searchParams } = new URL(request.url);
    const now = new Date();
    const todayStr = `${now.getFullYear()}-${String(now.getMonth() + 1).padStart(2, '0')}-${String(now.getDate()).padStart(2, '0')}`;
    const startOfMonth = `${now.getFullYear()}-${String(now.getMonth() + 1).padStart(2, '0')}-01`;

    const startDate = searchParams.get('startDate') || startOfMonth;
    const endDate = searchParams.get('endDate') || todayStr;
    const forceRefresh = searchParams.get('refresh') === 'true';

    const cacheKey = `memo_print_${startDate}_${endDate}`;
    if (!forceRefresh) {
      const cached = memoryCache.get(cacheKey);
      if (cached && Date.now() - cached.timestamp < CACHE_TTL_MS) {
        return NextResponse.json({
          success: true,
          data: cached.records,
          meta: cached.meta,
          cached: true,
        });
      }
    }

    let records = await fetchLiveInvoicesFromSokrio(startDate, endDate);
    let source = 'sokrio_live_api';

    const meta = {
      totalRecords: records.length,
      startDate,
      endDate,
      source,
    };

    memoryCache.set(cacheKey, {
      records,
      meta,
      timestamp: Date.now(),
    });

    return NextResponse.json({
      success: true,
      data: records,
      meta,
      cached: false,
    });
  } catch (error: any) {
    console.error('[Memo Print Report API Error]:', error);
    return NextResponse.json({
      success: true,
      data: [],
      meta: {
        totalRecords: 0,
        source: 'sokrio_live_api',
        error: error.message,
      },
      cached: false,
    });
  }
}
