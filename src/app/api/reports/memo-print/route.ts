function formatDateToDDMMYYYY(val: any): string {
  if (!val) return '';
  const s = String(val).trim();
  if (s.includes('/')) {
    const p = s.split('/');
    if (p.length === 3) {
      if (p[0].length === 4) return `${p[2].padStart(2, '0')}/${p[1].padStart(2, '0')}/${p[0]}`;
      return `${p[0].padStart(2, '0')}/${p[1].padStart(2, '0')}/${p[2]}`;
    }
  }
  if (s.includes('-')) {
    const p = s.split(' ')[0].split('-');
    if (p.length === 3) {
      if (p[0].length === 4) return `${p[2].padStart(2, '0')}/${p[1].padStart(2, '0')}/${p[0]}`;
      return `${p[0].padStart(2, '0')}/${p[1].padStart(2, '0')}/${p[2]}`;
    }
  }
  const d = new Date(val);
  if (!isNaN(d.getTime())) {
    const dd = String(d.getDate()).padStart(2, '0');
    const mm = String(d.getMonth() + 1).padStart(2, '0');
    return `${dd}/${mm}/${d.getFullYear()}`;
  }
  return s;
}

function formatTimeTo12Hour(val: any): string {
  if (!val) return '';
  const s = String(val).trim();
  const timePart = s.includes(' ') && s.includes(':') ? (s.split(' ').find(x => x.includes(':')) || s) : s;
  const match = timePart.match(/(\d{1,2}):(\d{2})(?::(\d{2}))?\s*(am|pm)?/i);
  if (match) {
    let [_, hStr, mStr, , ampm] = match;
    let h = parseInt(hStr, 10);
    const m = mStr.padStart(2, '0');
    let period = (ampm || '').toUpperCase();
    if (!period) {
      period = h >= 12 ? 'PM' : 'AM';
      if (h > 12) h -= 12;
      if (h === 0) h = 12;
    }
    return `${String(h).padStart(2, '0')}:${m} ${period}`;
  }
  return s;
}



async function fetchLiveInvoicesFromSokrio(): Promise<MemoPrintRecord[]> {
  const token = await getValidToken();
  const url = 'https://pvm.core.sokrio.com/api/v1/invoices?per_page=150';

  const res = await axios.get(url, {
    headers: { Authorization: `Bearer ${token}`, Accept: 'application/json' },
    timeout: 30000,
  });

  const invoices: any[] = res.data?.invoices || res.data?.data || [];
  if (invoices.length === 0) return [];

  return invoices.map((inv, idx) => {
    const srCode = String(inv.creator?.code || inv.ordered_by?.code || '').trim();
    const srName = String(inv.creator?.name || inv.ordered_by?.name || `SR ${srCode}`).trim();
    const srMeta = SR_METADATA[srCode] || { srPositionCode: 'DM-057', territory: 'Jatra Bari' };

    const createdAt = inv.created_at || '';
    const parts = createdAt.split(' ');
    const rawPrintingDate = parts[0] || '';
    const rawPrintingTime = parts.slice(1).join(' ') || '';
    const rawOrderDate = inv.order?.order_date || rawPrintingDate;

    return {
      id: `memo-live-${inv.id || idx + 1}`,
      cluster: 'Central',
      area: 'Central South',
      territory: srMeta.territory,
      dbCodeAutogenerated: 'MD11239',
      dbCode: 102267,
      dbName: 'M/S Ahamed Enterprise',
      dbType: 'Main DB',
      printerType: 'Web',
      srPositionCode: srMeta.srPositionCode,
      srCode: Number(srCode) || srCode,
      srName,
      orderMemoNo: inv.id || idx + 1,
      printingMemoNo: inv.id || idx + 1,
      orderDate: formatDateToDDMMYYYY(rawOrderDate),
      printingDate: formatDateToDDMMYYYY(rawPrintingDate),
      printingTime: formatTimeTo12Hour(rawPrintingTime),
    };
  });
}

export async function GET(request: NextRequest) {
  try {
    const { searchParams } = new URL(request.url);
    const now = new Date();
    const todayStr = `${now.getFullYear()}-${String(now.getMonth() + 1).padStart(2, '0')}-${String(now.getDate()).padStart(2, '0')}`;
    const startOfMonth = `${now.getFullYear()}-${String(now.getMonth() + 1).padStart(2, '0')}-01`;

    const startDate = searchParams.get('startDate') || startOfMonth;
    const endDate = searchParams.get('endDate') || todayStr;
    const forceRefresh = searchParams.get('refresh') === 'true';

    const cacheKey = `memo_print_${startDate}_${endDate}`;
    if (!forceRefresh) {
      const cached = memoryCache.get(cacheKey);
      if (cached && Date.now() - cached.timestamp < CACHE_TTL_MS) {
        return NextResponse.json({
          success: true,
          data: cached.records,
          meta: cached.meta,
          cached: true,
        });
      }
    }

    let records = await fetchLiveInvoicesFromSokrio();
    let source = 'sokrio_live_api';

    const meta = {
      totalRecords: records.length,
      startDate,
      endDate,
      source,
    };

    memoryCache.set(cacheKey, {
      records,
      meta,
      timestamp: Date.now(),
    });

    return NextResponse.json({
      success: true,
      data: records,
      meta,
      cached: false,
    });
  } catch (error: any) {
    console.error('[Memo Print Report API Error]:', error);
    return NextResponse.json({
      success: true,
      data: [],
      meta: {
        totalRecords: 0,
        source: 'sokrio_live_api',
        error: error.message,
      },
      cached: false,
    });
  }
}
